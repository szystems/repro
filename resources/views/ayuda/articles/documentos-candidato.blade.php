<div class="ayuda-articulo">
    <p class="lead">Adjunte documentos del candidato (DPI, antecedentes penales, etc.) desde el detalle de la orden.</p>

    <h5>Cómo subir</h5>
    <ol>
        <li>Abra la orden → expanda el evaluado.</li>
        <li>Sección <strong>Documentos</strong> → <strong>Subir Documento</strong>.</li>
        <li>Seleccione tipo de documento (incluye <strong>Tatuajes</strong>), archivo (máx. 10 MB) y notas opcionales.</li>
        <li>En tablet o celular puede <strong>tomar la fotografía</strong> o <strong>pegar una imagen</strong> (Ctrl+V) en la zona de subida.</li>
        <li>Confirme la subida.</li>
    </ol>

    <h5>Tipos comunes</h5>
    <ul>
        <li>DPI (frontal/reverso)</li>
        <li>Tatuajes</li>
        <li>Antecedentes penales / policiales</li>
        <li>Constancia laboral</li>
        <li>Otros según requerimientos de la orden</li>
    </ul>

    <h5>Verificación</h5>
    <p>REPRO revisa y marca documentos como verificados. Hasta entonces aparecen como pendientes de verificación.</p>
</div>
