<div class="ayuda-articulo">
    <p class="lead">Como usuario principal, administre las cuentas de su equipo en el portal cliente.</p>

    <h5>Acceso</h5>
    <p>Menú <strong>Mi Empresa → Usuarios</strong> (<code>/empresa/usuarios</code>). Solo visible para usuario principal. Desde aquí se crean y editan <strong>trabajadores</strong>; el titular no se elimina en este menú.</p>
    <p>Para desactivar al titular hay que hacerlo en REPRO: <strong>Administración → Usuarios</strong> (botón Eliminar). Eso no borra el historial: deja la cuenta sin acceso.</p>

    <h5>Crear usuario</h5>
    <ol>
        <li>Pulse crear nuevo usuario.</li>
        <li>Complete nombre, email y contraseña temporal.</li>
        <li>Asigne permisos individuales (ver órdenes, crear órdenes, subir documentos, ver reportes…).</li>
        <li>El trabajador recibirá acceso limitado según los permisos marcados.</li>
    </ol>

    <h5>Editar permisos</h5>
    <p>Puede modificar permisos en cualquier momento. Los cambios aplican en el próximo inicio de sesión del trabajador.</p>

    <div class="alert alert-info">
        <i class="bi bi-info-circle me-2"></i>
        El perfil por defecto de un trabajador <strong>no incluye</strong> crear órdenes ni ver reportes. Asígnelos explícitamente si los necesita.
    </div>
</div>
