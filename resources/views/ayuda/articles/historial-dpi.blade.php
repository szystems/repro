<div class="ayuda-articulo">
    <p class="lead">Busque evaluaciones previas de un candidato en todas las órdenes del sistema.</p>

    <h5>Acceso</h5>
    <p>Menú <strong>Evaluaciones → Historial por DPI o nombre</strong> (<code>/cuestionarios/historial-dpi</code>).</p>

    <h5>Búsqueda</h5>
    <ul>
        <li>Ingrese DPI completo (13 dígitos) o parte del nombre/apellido.</li>
        <li>Resultados muestran todas las evaluaciones encontradas con empresa, fecha y tipo de servicio.</li>
        <li>Click en un resultado para abrir el cuestionario correspondiente.</li>
        <li>No incluye evaluados de <strong>órdenes archivadas</strong>. Para ver esas órdenes use el filtro Vista → Órdenes archivadas. Ver <a href="{{ route('ayuda.show', 'archivar-ordenes') }}">Archivar órdenes</a>.</li>
    </ul>

    <p>La visibilidad para clientes depende de la configuración <em>historial_visible_empresa</em> en Configuración del sistema.</p>
</div>
