    <h5><i class="bi bi-list me-2"></i>Menú lateral</h5>
    <p>El menú izquierdo organiza los módulos por área. Solo verá las opciones para las que tiene permiso asignado:</p>
    <ul>
        <li><strong>Panel de Control</strong> — resumen de órdenes, evaluados y cuestionarios.</li>
        <li><strong>Evaluaciones</strong> — gestión de cuestionarios completados e historial por DPI.</li>
        <li><strong>Órdenes de Evaluación</strong> — listado, estadísticas y reporte por empresas.</li>
        <li><strong>Empresas</strong> — clientes registrados en el sistema.</li>
        <li><strong>Sedes REPRO</strong> — ubicaciones y contacto.</li>
        <li><strong>Calendario</strong> — programación de citas.</li>
        <li><strong>Administración</strong> — usuarios (listado en <strong>Excel</strong> o PDF), roles, configuración y finanzas (según su rol).</li>
        <li><strong>Ayuda</strong> — Centro de Ayuda y la <a href="{{ route('ayuda.show', 'guia-usuario-sigor') }}">Guía de usuario SIGOR</a> (se ve en el navegador).</li>
    </ul>

    <h5><i class="bi bi-shield me-2"></i>Roles REPRO</h5>
    <ul>
        <li><strong>Administrador</strong> — acceso total, incluyendo configuración y seguridad.</li>
        <li><strong>Operativo REPRO</strong> — acceso según permisos del rol asignado (poligrafista, recepción, etc.).</li>
    </ul>

    <h5><i class="bi bi-whatsapp me-2"></i>Atajos que usa el equipo a diario</h5>
    <ul>
        <li><strong>WhatsApp al candidato</strong> — botón verde en Gestión de Cuestionario (si hay teléfono).</li>
        <li><strong>Programó / Encargado / Entrevistó</strong> — tres roles distintos en la orden. «Autoasignarme entrevista» no cambia quién programó ni el encargado.</li>
        <li><strong>Enlace del candidato</strong> — 15 días al crear o rehabilitar. Ver <a href="{{ route('ayuda.show', 'enlaces-candidato') }}">Enlaces del candidato</a>.</li>
    </ul>

