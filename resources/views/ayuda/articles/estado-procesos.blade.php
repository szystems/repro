<div class="ayuda-articulo">
    <p class="lead">Vista de solo lectura del avance de cuestionarios de sus candidatos.</p>

    <h5>Acceso</h5>
    <p>Menú <strong>Cuestionarios → Estado de Procesos</strong> (<code>/cuestionarios</code>).</p>

    <h5>Qué muestra</h5>
    <ul>
        <li>Listado filtrado a candidatos de su empresa.</li>
        <li>Estado del cuestionario (completado, pendiente, etc.).</li>
        <li>Empresa, tipo de formulario y fecha.</li>
    </ul>

    <h5>Limitaciones</h5>
    <ul>
        <li>No puede editar respuestas del candidato.</li>
        <li>No genera informes Word (función REPRO).</li>
        <li>Para acciones sobre el enlace, use el detalle de la orden.</li>
    </ul>
</div>
