    <p class="lead">Administración de empresas cliente registradas en REPRO.</p>

    <h5>Listado (<code>/empresas</code>)</h5>
    <ul>
        <li>Buscar por nombre, NIT o estado (activa/inactiva).</li>
        <li>Exportar listado a PDF.</li>
    </ul>

    <h5>Crear / editar empresa</h5>
    <ul>
        <li>Datos fiscales, contacto, logo y sedes/regiones de la empresa.</li>
        <li>Configuración de confidencialidad entre reclutadores (si aplica).</li>
    </ul>

    <h5>Usuarios de la empresa</h5>
    <p>Los usuarios del portal cliente se gestionan desde el propio portal (Mi Empresa → Usuarios) por el usuario principal. REPRO crea el usuario principal al registrar la empresa.</p>
