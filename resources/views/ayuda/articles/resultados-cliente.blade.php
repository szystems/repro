<div class="ayuda-articulo">
    <p class="lead">Consulte y descargue los resultados de evaluación cuando REPRO los habilite.</p>

    <h5>¿Cuándo aparecen?</h5>
    <p>REPRO controla la visibilidad. Los resultados no son automáticos al completar el cuestionario — REPRO debe subirlos y marcarlos visibles.</p>

    <h5>Tipos de resultado</h5>
    <ul>
        <li><strong>Resultado preliminar</strong> — avance o resultado parcial. El título incluye el <strong>nombre del candidato</strong> (útil al capturar o reenviar).</li>
        <li><strong>Resultado final</strong> — informe definitivo de la evaluación.</li>
    </ul>

    <h5>Cómo descargar</h5>
    <ol>
        <li>Abra la orden → expanda el evaluado.</li>
        <li>Sección <strong>Archivos de Resultado</strong>.</li>
        <li>Descargue el PDF disponible (preliminar o final).</li>
    </ol>

    <h5>¿A quién le llega el correo?</h5>
    <p>Al <strong>reclutador asignado</strong>, si lo hay. Si no, a quien creó la orden (cuando la creó la empresa) o al titular si la creó REPRO. El gerente ve los procesos en el portal; el correo no se dispara a toda la empresa.</p>

    <p>Si no ve resultados, contacte a REPRO por WhatsApp (menú Contacto) o verifique que la evaluación esté completada.</p>
</div>
