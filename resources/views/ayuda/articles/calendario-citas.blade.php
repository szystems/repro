<div class="ayuda-articulo">
    <p class="lead">Programe citas de evaluación presencial o virtual desde el calendario o desde el detalle de la orden.</p>

    <h5>Desde el calendario (<code>/calendario</code>)</h5>
    <ul>
        <li>Vista mensual con evaluados programados por día.</li>
        <li>Click en un día para ver detalle horario.</li>
        <li>No muestra citas de órdenes archivadas. Ver <a href="{{ route('ayuda.show', 'archivar-ordenes') }}">Archivar órdenes</a>.</li>
    </ul>

    <h5>Desde el detalle de la orden</h5>
    <ol>
        <li>Expanda el evaluado.</li>
        <li>Pulse <strong>Programar cita</strong>.</li>
        <li>Complete: fecha, hora inicio/fin, sede REPRO y modalidad (presencial/virtual).</li>
        <li>Confirme — el estado de programación cambia a «Programado».</li>
    </ol>

    <h5>Reprogramar o cancelar</h5>
    <ul>
        <li>Desde el calendario del día o cambiando el estado de programación en la orden.</li>
        <li>Registre motivo u observación cuando aplique (campo opcional expandible).</li>
    </ul>
</div>
