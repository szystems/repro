<div class="ayuda-articulo">
    <p class="lead">REPRO genera informes Word (.docx) a partir de las respuestas del cuestionario del candidato.</p>

    <h5>Desde el detalle de la orden</h5>
    <ol>
        <li>Expanda el evaluado.</li>
        <li>Pulse <strong>Descargar informe Word (.docx)</strong>.</li>
        <li>El archivo se descarga directamente con los datos actuales del cuestionario.</li>
    </ol>

    <h5>Desde la edición del cuestionario</h5>
    <ol>
        <li>Vaya a <strong>Gestión de Cuestionario</strong> → seleccione el cuestionario → <strong>Editar</strong>.</li>
        <li>La sección roja <strong>EDITAR CONTENIDO DE CUESTIONARIO</strong> es el PDF que llenó el candidato.</li>
        <li>A partir de <strong>INICIO DE REDACCIÓN DE INFORME EN WORD</strong> va primero el <strong>Resultado de evaluación (primera hoja)</strong>, luego las <strong>Tablas para informe</strong> y la <strong>Redacción del informe Word</strong>.</li>
        <li>En la sección «Vista previa del borrador Word», el sistema genera una previsualización HTML.</li>
        <li>La generación puede tardar unos segundos; si excede 90 segundos se cancela automáticamente.</li>
        <li>También puede descargar el borrador Word desde el modal de vista previa del informe.</li>
    </ol>

    <h5>Secciones del informe</h5>
    <ul>
        <li>El informe incluye datos personales, laborales, familiares y secciones específicas según el tipo de formulario.</li>
        <li>Las secciones sin datos (ej. deudas vacías) no aparecen en el documento.</li>
        <li>La sección TATUAJES solo muestra información de tatuajes, no documentos adjuntos.</li>
    </ul>

    <div class="alert alert-warning">
        <i class="bi bi-exclamation-triangle me-2"></i>
        Guarde los cambios en el cuestionario antes de generar la vista previa; el sistema guarda un borrador automáticamente al abrirla.
    </div>
</div>
