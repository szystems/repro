<div class="ayuda-articulo">
    <p class="lead">REPRO genera informes Word (.docx) a partir de las respuestas del cuestionario del candidato.</p>

    <h5>Desde el detalle de la orden</h5>
    <ol>
        <li>Expanda el evaluado.</li>
        <li>Pulse <strong>Descargar informe Word (.docx)</strong>.</li>
        <li>El archivo se descarga directamente con los datos actuales del cuestionario.</li>
    </ol>

    <h5>Desde la edición del cuestionario</h5>
    <ol>
        <li>Vaya a <strong>Gestión de Cuestionario</strong> → seleccione el cuestionario → <strong>Editar</strong>.</li>
        <li>La sección roja <strong>EDITAR CONTENIDO DE CUESTIONARIO</strong> es el PDF que llenó el candidato.</li>
        <li>A partir de <strong>INICIO DE REDACCIÓN DE INFORME EN WORD</strong> va el <strong>Resultado de evaluación (primera y última hoja)</strong>, las <strong>Tablas para informe</strong>, la <strong>Redacción del informe Word</strong> y (si hay imágenes subidas) los <strong>Anexos de papelería en informe Word</strong>.</li>
        <li>En la sección «Vista previa del borrador Word», el sistema genera una previsualización HTML.</li>
        <li>La generación puede tardar unos segundos; si excede 90 segundos se cancela automáticamente.</li>
        <li>También puede descargar el borrador Word desde el modal de vista previa del informe.</li>
    </ol>

    <h5>Secciones del informe</h5>
    <ul>
        <li>El informe incluye datos personales, laborales, familiares y secciones específicas según el tipo de formulario.</li>
        <li>Las secciones sin datos (ej. deudas vacías) no aparecen en el documento.</li>
        <li>En <strong>polígrafo y VSA preempleo</strong>: hijos vacíos muestran «No tiene» en la primera columna; el bloque <strong>Ampliación de información laboral</strong> va pegado al historial; la fila <strong>Validación de constancia de estudios</strong> queda vacía para que la llene el evaluador (no se copia el sí/no del candidato). Los totales de deudas van en 11 puntos.</li>
        <li>La tabla <strong>Información complementaria</strong> va en fuente 12.</li>
        <li>En la orden, dentro de <strong>Documentos</strong>, la columna <strong>En el Word</strong> marca cada imagen (JPG o PNG). Se guarda al marcarla. Si hay dos archivos del mismo documento, se elige solo el que debe ir al final. Los PDF no se pegan.</li>
        <li>La sección TATUAJES solo muestra información de tatuajes, no documentos adjuntos.</li>
    </ul>

    <h5>Informe preliminar (cliente) y 1ª hoja</h5>
    <p>Al guardar el cuestionario, el sistema copia el <strong>resultado y observaciones de la primera hoja</strong> al informe preliminar HTML de la ficha de orden (lo que ve el cliente cuando REPRO lo libera). Si REPRO editó el preliminar a mano en la ficha, ese texto <strong>no se sobrescribe</strong> al guardar de nuevo el cuestionario.</p>

    <div class="alert alert-warning">
        <i class="bi bi-exclamation-triangle me-2"></i>
        Guarde los cambios en el cuestionario antes de generar la vista previa; el sistema guarda un borrador automáticamente al abrirla.
    </div>
</div>
